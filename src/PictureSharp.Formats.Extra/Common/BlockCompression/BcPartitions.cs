    ];

    // Bits 2i..2i+1: the subset of pixel i.
    private static ReadOnlySpan<uint> Three =>
    [
        0xaa685050, 0x6a5a5040, 0x5a5a4200, 0x5450a0a8, 0xa5a50000, 0xa0a05050, 0x5555a0a0, 0x5a5a5050,

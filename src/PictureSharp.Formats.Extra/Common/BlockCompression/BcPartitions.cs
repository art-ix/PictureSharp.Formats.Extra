    private static ReadOnlySpan<byte> AnchorTwo =>
    [
        15, 15, 15, 15, 15, 15, 15, 15, 15, 15, 15, 15, 15, 15, 15, 15,
        15, 2, 8, 2, 2, 8, 8, 15, 2, 8, 2, 2, 8, 8, 2, 2,
        15, 15, 6, 8, 2, 8, 15, 15, 2, 8, 2, 2, 2, 15, 15, 6,
        6, 2, 6, 8, 15, 15, 2, 2, 15, 15, 15, 15, 15, 2, 2, 15,
    ];

    private static ReadOnlySpan<byte> AnchorThreeSecond =>
    [
        3, 3, 15, 15, 8, 3, 15, 15, 8, 8, 6, 6, 6, 5, 3, 3,
        3, 3, 8, 15, 3, 3, 6, 10, 5, 8, 8, 6, 8, 5, 15, 15,
        8, 15, 3, 5, 6, 10, 8, 15, 15, 3, 15, 5, 15, 15, 15, 15,
        3, 15, 5, 5, 5, 8, 5, 10, 5, 10, 8, 13, 15, 12, 3, 3,
    ];

    private static ReadOnlySpan<byte> AnchorThreeThird =>
    [
        15, 8, 8, 3, 15, 15, 3, 8, 15, 15, 15, 15, 15, 15, 15, 8,
        15, 8, 15, 3, 15, 8, 15, 8, 3, 15, 6, 10, 15, 15, 10, 8,
        15, 3, 15, 10, 10, 8, 9, 10, 6, 15, 8, 15, 3, 6, 6, 8,
        15, 3, 15, 15, 15, 15, 15, 15, 15, 15, 15, 15, 3, 15, 15, 8,
    ];

    /// <summary>The subset (0 to <paramref name="subsets"/> - 1) of pixel <paramref name="pixel"/>.</summary>
    public static int Subset(int subsets, int partition, int pixel) => subsets switch
    {
        1 => 0,
        2 => (Two[partition] >> pixel) & 1,
        _ => (int)(Three[partition] >> (2 * pixel)) & 3,
    };

    /// <summary>Whether the pixel is the anchor of its subset, whose index is stored with one bit less.</summary>
    public static bool IsAnchor(int subsets, int partition, int pixel) => pixel == 0 || subsets switch
    {
        1 => false,
        2 => pixel == AnchorTwo[partition],
        _ => pixel == AnchorThreeSecond[partition] || pixel == AnchorThreeThird[partition],
    };

    /// <summary>Interpolation weights for 2-, 3- and 4-bit indices.</summary>
    public static ReadOnlySpan<byte> Weights(int bits) => bits switch
    {
        2 => [0, 21, 43, 64],
        3 => [0, 9, 18, 27, 37, 46, 55, 64],
        _ => [0, 4, 9, 13, 17, 21, 26, 30, 34, 38, 43, 47, 51, 55, 60, 64],
    };
}

#!/usr/bin/env python3
"""Writes the X11 colour names XPM files use (src/PictureSharp.Formats.Extra/Xpm/X11Colors.cs) from X.Org's rgb.txt.

Names are matched without case and spaces, as libXpm and ImageMagick match them.

Run with:  python3 -I tests/assets/make_x11_colors.py [/usr/share/X11/rgb.txt]
"""
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(ROOT, "..", "..", "src", "PictureSharp.Formats.Extra", "Xpm", "X11Colors.cs")


def main():
    source = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/X11/rgb.txt"
    colors = {}
    for line in open(source, encoding="ascii"):
        if line.startswith("!") or not line.strip():
            continue
        r, g, b, *name = line.split()
        key = "".join(name).lower()
        value = (int(r) << 16) | (int(g) << 8) | int(b)
        assert colors.get(key, value) == value, key
        colors[key] = value
    entries = [f"{k}={v:06x}" for k, v in sorted(colors.items())]
    lines = []
    line = ""
    for e in entries:
        if len(line) + len(e) + 1 > 100:
            lines.append(line)
            line = ""
        line += e + ";"
    lines.append(line)
    body = "\n".join(f'        "{l}" +' for l in lines).rstrip(" +")
    with open(TARGET, "w", newline="\n") as f:
        f.write(f"""// <auto-generated>tests/assets/make_x11_colors.py from X.Org rgb.txt; {len(colors)} names.</auto-generated>
namespace PictureSharp.Formats.Xpm;

internal static partial class X11Colors
{{
    /// <summary>Lower-case names without spaces and their RRGGBB values, as <c>name=rrggbb;</c>.</summary>
    private const string Table =
{body};
}}
""")
    print(len(colors), "names")


if __name__ == "__main__":
    main()
